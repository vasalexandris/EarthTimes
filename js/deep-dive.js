/**
 * Returns deep dive data for a topic key, or creates a rich fallback from title & text.
 */
export function getDeepDiveData(keyOrTitle, fallbackSummary = '', contextEntityName = '') {
  const normKey = (keyOrTitle || '').toLowerCase();
  
  // Direct key lookup
  if (DEEP_DIVE_ENTRIES[normKey]) {
    return DEEP_DIVE_ENTRIES[normKey];
  }

  // Substring match
  if (normKey.includes('bauhaus') || normKey.includes('μπαουχαους')) {
    return DEEP_DIVE_ENTRIES.bauhaus;
  }
  if (normKey.includes('κοβενταρ') || normKey.includes('ρηγα') || normKey.includes('βιβλιοθηκη')) {
    return DEEP_DIVE_ENTRIES.koventario;
  }
  if (normKey.includes('ρολοι') || normKey.includes('μαματσιο') || normKey.includes('καμπαναριο')) {
    return DEEP_DIVE_ENTRIES.mamatsios;
  }
  if (normKey.includes('κροκο') || normKey.includes('σαφραν') || normKey.includes('saffron')) {
    return DEEP_DIVE_ENTRIES.krokos;
  }
  if (normKey.includes('ακροπολ') || normKey.includes('παρθενων')) {
    return DEEP_DIVE_ENTRIES.acropolis;
  }
  if (normKey.includes('βραδεμβουργ') || normKey.includes('brandenburg') || normKey.includes('τειχοσ') || normKey.includes('τειχους')) {
    return DEEP_DIVE_ENTRIES.brandenburg;
  }
  if (normKey.includes('καναλι') || normKey.includes('amsterdam') || normKey.includes('gracht')) {
    return DEEP_DIVE_ENTRIES.amsterdam_canals;
  }
  if (normKey.includes('γεφυρα') && normKey.includes('καρολ') || normKey.includes('αστρονομικο')) {
    return DEEP_DIVE_ENTRIES.charles_bridge;
  }

  // Dynamic Rich Fallback
  return {
    title: keyOrTitle || 'Ιστορικό Αφιέρωμα & Πολιτιστική Ανάλυση',
    badge: 'Εκτενής Παρουσίαση',
    category: contextEntityName || 'Παγκόσμιο Χρονικό EarthTimes',
    epoch: 'Ιστορική & Σύγχρονη Διάσταση',
    image: 'https://images.unsplash.com/photo-1451187580459-43490279c0fa?w=1000&auto=format&fit=crop&q=80',
    caption: `Αφιέρωμα: ${keyOrTitle}`,
    summary: fallbackSummary || 'Αναλυτική καταγραφή ιστορικού οροσήμου και πολιτιστικής παρακαταθήκης.',
    sections: [
      {
        heading: '1. Ιστορικό Πλαίσιο & Σημασία',
        content: fallbackSummary ? `<p class="leading-relaxed text-slate-200">${fallbackSummary}</p>` : `<p class="leading-relaxed text-slate-200">Σημαντικό σημείο αναφοράς με συνεχή επίδραση στην κοινωνική και πολιτιστική ταυτότητα της περιοχής.</p>`
      },
      {
        heading: '2. Πολιτιστική Παρακαταθήκη & Μνήμη',
        content: `Το ορόσημο αυτό αποτελεί αναπόσπαστο μέρος του παγκόσμιου αρχείου μνήμης του EarthTimes. Μέσα από αρχειακές μαρτυρίες, φωτογραφικά τεκμήρια και επιτόπια έρευνα, αναδεικνύεται η σύνδεση του τόπου με την ανθρώπινη δημιουργία.`
      }
    ]
  };
}
